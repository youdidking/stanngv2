import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
let clock=0,calls=0;
const context={console,AbortController,Uint8Array,setTimeout,clearTimeout,performance:{now:()=>++clock},fetch:async()=>{calls++;throw TypeError('TLS or browser failure');}};
context.globalThis=context;vm.runInNewContext(fs.readFileSync('src/ui/network.js','utf8'),context);
const N=context.NLNetwork;
assert.equal(N.median([2,100,4]),4);
const summary=N.summary([{ok:true,ms:100},{ok:false,ms:1},{ok:true,ms:120}]);
assert.equal(summary.ms,110);assert.equal(summary.jitter,20);assert.equal(summary.noReply,33);assert.equal(summary.ok,true);
const failure=await N.sample('https://104.16.1.1/cdn-cgi/trace',{mode:'no-cors',timeout:100},3);
assert.equal(calls,3,'Raw IP must actually be attempted three times');assert.equal(failure.ok,false);assert.equal(failure.ms,null,'Quick errors must not be successful RTT');assert(failure.attemptMs>=1);assert.equal(failure.replies,0);
context.fetch=async()=>({type:'opaque'});
const opaque=await N.sample('https://104.16.1.1/cdn-cgi/trace',{mode:'no-cors'},3);assert.equal(opaque.ok,true);assert.equal(opaque.replies,3);
context.fetch=async()=>({ok:true,json:async()=>({ok:true,version:'wrong'})});
assert.equal((await N.timed('https://panel.example/api/ping',{check:'health'})).ok,false,'Worker health must validate version');
context.fetch=async()=>({ok:true,json:async()=>({ok:true,version:'2.5.3'})});
assert.equal((await N.timed('https://panel.example/api/ping',{check:'health'})).ok,true);
context.fetch=async()=>({ok:true,json:async()=>({Status:0,Answer:[]})});
assert.equal((await N.timed('https://dns.example/query',{check:'dns'})).ok,false,'A JSON response without DNS answers is not a valid DoH test');
let running=0,maximum=0;
await N.bounded(Array.from({length:10},(_,i)=>i),3,async()=>{running++;maximum=Math.max(maximum,running);await new Promise(r=>setTimeout(r,5));running--;return true;});assert(maximum<=3);
const cancelled=new AbortController();cancelled.abort();assert.equal((await N.sample('https://example.com',{signal:cancelled.signal},3)).attempts,0);
const app=fs.readFileSync('src/ui/app.js','utf8');assert(!app.includes('NEEDS CLIENT SNI TEST'));assert(!app.includes("if (entry.isRawIp) return"));assert(!app.includes('sni-scanner.py'));
console.log('PASS browser diagnostics: median/jitter, real repeated raw-IP attempts, no quick-error false positives, health/DoH validation, bounded concurrency and cancellation.');
